import { gregorianToHijri } from './islamicCalendar';

export const getHijriDate = () => {
  const date = new Date();
  try {
    const hijri = gregorianToHijri(date);
    return { day: hijri.day, month: hijri.month, year: hijri.year };
  } catch (e) {
    console.error("Hijri Date Error", e);
    return { day: 1, month: 1, year: 1446 };
  }
};

export const getNextEvent = () => {
  const { day, month } = getHijriDate();

  // Sort events by month then day
  const sorted = [...EVENTS_DATA].sort((a, b) => {
    if (a.month !== b.month) return a.month - b.month;
    return a.day[0] - b.day[0];
  });

  // Find next event in current year
  let next = sorted.find(e =>
    (e.month > month) || (e.month === month && e.day[e.day.length - 1] >= day)
  );

  // If no event left this year, take the first one next year
  if (!next) next = sorted[0];

  return next;
};

/**
 * Calculate days remaining until an event
 * Uses lunar month approximation (30 days per month)
 */
export const getDaysRemaining = (event: { month: number; day: number[] }): number => {
  const { day, month } = getHijriDate();

  let currentTotal = month * 30 + day;
  let eventTotal = event.month * 30 + event.day[0];

  // If event is in the past (next year), add approximate lunar year days
  if (eventTotal < currentTotal) {
    eventTotal += 354; // Approximate days in lunar year
  }

  return Math.max(0, eventTotal - currentTotal);
};
